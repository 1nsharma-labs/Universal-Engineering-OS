def get_canvas_catalog() -> Dict[str, Any]:
    return {"nodes": [{"type": k, **v} for k, v in NODE_CATALOG.items()]}


def compile_visual_graph(nodes: List[Dict[str, Any]], edges: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Compiles a visual node graph into docker-compose YAML, .env wiring, and Mermaid diagram."""
    if not nodes:
        return {"ok": False, "error": "Graph must include at least one architecture node."}

    id_to_node: Dict[str, Dict[str, Any]] = {}
    deps_map: Dict[str, List[str]] = {}

    for idx, n in enumerate(nodes):
        ntype = str(n.get("type", "fastapi")).lower()
        spec = NODE_CATALOG.get(ntype, NODE_CATALOG["fastapi"])
        nid = str(n.get("id") or f"{ntype}-{idx+1}").lower().replace(" ", "-")
        id_to_node[nid] = {"id": nid, "type": ntype, "label": n.get("label") or spec["label"], **spec}
        deps_map[nid] = []

    mermaid_lines = ["flowchart LR"]
    for nid, info in id_to_node.items():
        mermaid_lines.append(f'  {nid.replace("-", "_")}["{info["label"]} (:{info["port"]})"]')

    for edge in edges:
        src = str(edge.get("source", "")).lower().replace(" ", "-")
        tgt = str(edge.get("target", "")).lower().replace(" ", "-")
        if src in id_to_node and tgt in id_to_node and src != tgt:
            if tgt not in deps_map[src]:
                deps_map[src].append(tgt)
            mermaid_lines.append(f"  {src.replace('-', '_')} --> {tgt.replace('-', '_')}")

    compose_lines = [
        "# Generated by UNIFORGE Visual Node Architecture Compiler (Milestone 7)",
        "name: uniforge-visual-stack",
        "",
        "services:",
    ]
    env_lines = ["# Generated .env wiring"]

    for nid, info in id_to_node.items():
        compose_lines.append(f"  {nid}:")
        compose_lines.append(f"    image: {info['image']}")
        compose_lines.append("    ports:")
        compose_lines.append(f'      - "{info["port"]}:{info["port"]}"')
        if info.get("command"):
            compose_lines.append(f'    command: "{info["command"]}"')

        env_vars = dict(info.get("env", {}))
        for dep in deps_map[nid]:
            dep_info = id_to_node[dep]
            if dep_info["type"] == "postgres":
                env_vars["DATABASE_URL"] = f"postgresql://uniforge:${{POSTGRES_PASSWORD:-changeme}}@{dep}:5432/app_db"
            elif dep_info["type"] == "redis":
                env_vars["REDIS_URL"] = f"redis://{dep}:6379/0"
            elif dep_info["type"] == "qdrant":
                env_vars["QDRANT_URL"] = f"http://{dep}:6333"
            elif dep_info["type"] == "ollama":
                env_vars["OLLAMA_HOST"] = f"http://{dep}:11434"
            elif dep_info["type"] == "fastapi" or dep_info["type"] == "spring-boot":
                env_vars["API_BASE_URL"] = f"http://{dep}:{dep_info['port']}"

        if env_vars:
            compose_lines.append("    environment:")
            for k, v in env_vars.items():
                compose_lines.append(f'      {k}: "{v}"')
                env_lines.append(f"{k}={v}")

        if deps_map[nid]:
            compose_lines.append("    depends_on:")
            for dep in deps_map[nid]:
                compose_lines.append(f"      - {dep}")

        compose_lines.append("    restart: unless-stopped")
        compose_lines.append("")

    return {
        "ok": True,
        "node_count": len(id_to_node),
        "edge_count": sum(len(v) for v in deps_map.values()),
        "mermaid": "\n".join(mermaid_lines),
        "docker_compose_yaml": "\n".join(compose_lines),
        "env_template": "\n".join(dict.fromkeys(env_lines)),
    }
