def run_autonomous_build(prompt: str, stack: str = "fastapi", write_to_disk: bool = False) -> Dict[str, Any]:
    """Executes Architect -> Coder -> Tester autonomous multi-agent workflow."""
    run_id = f"agent-{uuid.uuid4().hex[:8]}"
    slug = _slugify(prompt)
    start = time.perf_counter()

    # Step 1: Architect Agent
    architect_plan = {
        "agent": "ArchitectAgent",
        "project_slug": slug,
        "selected_stack": stack,
        "security_gates": ["Zero-Trust non-root container", "No hardcoded secrets", "Automated LSP static check"],
        "components": ["API / App Entrypoint", "Automated Verification Test", "Observability Health Endpoint"],
    }

    # Step 2: Coder Agent
    files = _generate_stack_files(prompt, stack, slug)

    # Step 3: Tester Agent (runs real LSP diagnostics on every generated file)
    verification_reports = []
    all_passed = True
    for filename, content in files.items():
        ext = Path(filename).suffix.lower()
        lang = {".py": "python", ".json": "json", ".ts": "typescript", ".tsx": "typescript", ".js": "javascript"}.get(ext, "")
        if lang:
            diag = analyze_diagnostics(lang, content)
            if not diag["valid"]:
                all_passed = False
            verification_reports.append({
                "file": filename,
                "language": lang,
                "passed": diag["valid"],
                "error_count": diag["error_count"],
                "diagnostics": diag["diagnostics"],
            })
        else:
            verification_reports.append({"file": filename, "language": "text", "passed": True, "error_count": 0, "diagnostics": []})

    written_path = None
    if write_to_disk:
        target_dir = GENERATED_DIR / slug
        target_dir.mkdir(parents=True, exist_ok=True)
        for rel_name, content in files.items():
            file_path = target_dir / rel_name
            file_path.parent.mkdir(parents=True, exist_ok=True)
            file_path.write_text(content, encoding="utf-8")
        written_path = str(target_dir.relative_to(HUB_ROOT))

    duration_ms = round((time.perf_counter() - start) * 1000, 2)
    record = {
        "run_id": run_id,
        "status": "PASSED" if all_passed else "NEEDS_HEALING",
        "prompt": prompt,
        "stack": stack,
        "duration_ms": duration_ms,
        "written_path": written_path,
        "agents_trace": [
            {"stage": 1, "agent": "ArchitectAgent", "status": "COMPLETED", "summary": f"Designed {slug} on {stack}"},
            {"stage": 2, "agent": "CoderAgent", "status": "COMPLETED", "summary": f"Generated {len(files)} source files"},
            {"stage": 3, "agent": "TesterAgent", "status": "PASSED" if all_passed else "FAILED", "summary": f"Verified {len(verification_reports)} files via LSP/AST"},
        ],
        "architect_plan": architect_plan,
        "generated_files": files,
        "verification_reports": verification_reports,
    }
    _AGENT_RUNS.insert(0, {k: record[k] for k in ("run_id", "status", "prompt", "stack", "duration_ms", "written_path")})
    del _AGENT_RUNS[25:]
    return record


def run_self_healing_sre(error_log: str, service_name: str = "control-plane") -> Dict[str, Any]:
    """Analyzes CI/Prometheus/Langfuse failure traces and synthesizes a deterministic remediation patch."""
    log = (error_log or "").strip()
    low = log.lower()

    if "modulenotfounderror" in low or "no module named" in low:
        match = re.search(r"no module named ['\"]([^'\"]+)['\"]", log, re.IGNORECASE)
        pkg = match.group(1) if match else "missing-package"
        return {
            "ok": True,
            "service": service_name,
            "incident_type": "MISSING_PYTHON_DEPENDENCY",
            "severity": "HIGH",
            "root_cause": f"Python runtime is missing required module `{pkg}`.",
            "auto_patch_diff": f"--- a/requirements.txt\n+++ b/requirements.txt\n@@ -1,3 +1,4 @@\n+{pkg}\n",
            "remediation_command": f"pip install {pkg} && python devhub.py test",
            "confidence": 0.97,
        }

    if "eaddrinuse" in low or "address already in use" in low or "port" in low and "in use" in low:
        return {
            "ok": True,
            "service": service_name,
            "incident_type": "PORT_CONFLICT",
            "severity": "MEDIUM",
            "root_cause": "Target TCP port is already bound by an existing process or container.",
            "auto_patch_diff": "--- a/devhub.py\n+++ b/devhub.py\n- run_server(port=7000)\n+ run_server(port=7001)\n",
            "remediation_command": "python devhub.py studio --port 7001",
            "confidence": 0.94,
        }

    if "oomkilled" in low or "out of memory" in low or "memoryerror" in low:
        return {
            "ok": True,
            "service": service_name,
            "incident_type": "CONTAINER_OOM_KILLED",
            "severity": "CRITICAL",
            "root_cause": "Container exceeded Kubernetes/Docker memory ceiling.",
            "auto_patch_diff": "--- a/cloud/helm/uniforge-cloud/values.yaml\n+++ b/cloud/helm/uniforge-cloud/values.yaml\n- memory: \"2Gi\"\n+ memory: \"4Gi\"\n",
            "remediation_command": "helm upgrade uniforge-cloud cloud/helm/uniforge-cloud --set resources.limits.memory=4Gi",
            "confidence": 0.92,
        }

    if "connection refused" in low or "could not connect" in low:
        return {
            "ok": True,
            "service": service_name,
            "incident_type": "UPSTREAM_DEPENDENCY_UNREACHABLE",
            "severity": "HIGH",
            "root_cause": "Dependent database, Redis, or Ollama service is stopped or unreachable.",
            "auto_patch_diff": "# Ensure infra stack healthcheck passes before app start\n- depends_on: [postgres]\n+ depends_on:\n+   postgres:\n+     condition: service_healthy\n",
            "remediation_command": "python devhub.py up && python devhub.py ps",
            "confidence": 0.91,
        }

    if "syntaxerror" in low:
        return {
            "ok": True,
            "service": service_name,
            "incident_type": "SYNTAX_REGRESSION",
            "severity": "HIGH",
            "root_cause": "Invalid source syntax introduced in recent commit.",
            "auto_patch_diff": "# Run automated LSP diagnostics to pinpoint exact line & column\n",
            "remediation_command": "python devhub.py validate && python devhub.py test",
            "confidence": 0.90,
        }

    return {
        "ok": True,
        "service": service_name,
        "incident_type": "GENERAL_RUNTIME_ANOMALY",
        "severity": "MEDIUM",
        "root_cause": f"Detected anomaly in `{service_name}` telemetry trace.",
        "auto_patch_diff": "# Recommend isolating service in Zero-Trust Sandbox & inspecting Prometheus metrics\n",
        "remediation_command": "python devhub.py validate && python devhub.py test",
        "confidence": 0.78,
    }


def list_agent_runs() -> Dict[str, Any]:
    return {"count": len(_AGENT_RUNS), "runs": _AGENT_RUNS}
