export function composeSrcDoc(files: Record<string, string>): string {
  const html = files['index.html'] || '<h1>Empty Preview</h1>';
  const css = files['styles.css'] || '';
  const js = files['app.js'] || '';
  return html
    .replace('<link rel="stylesheet" href="styles.css" />', `<style>${css}</style>`)
    .replace('<script src="app.js"></script>', `<script>${js}</script>`);
}

export async function runWorkbenchGeneration(
  prompt: string,
  mode: WorkbenchMode
): Promise<{ reply: string; files: Record<string, string> }> {
  let generatedBackendFiles: Record<string, string> = {};
  let stackSummary: string[] = ['UNIFORGE OS', 'React', 'TypeScript', 'Docker'];
  let reply = '';

  try {
    if (mode === 'factory-5layer') {
      const res = await fetch('/api/v1/factory/assemble', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ prompt, target_cloud: 'gcp', write_artifacts: false }),
      });
      if (res.ok) {
        const job = await res.json();
        const techs = (job.layers?.[1]?.selected_technologies || []).map((t: { name: string }) => t.name);
        if (techs.length) stackSummary = techs;
        generatedBackendFiles = {
          ...(job.generated_files_content || {}),
          'docker-compose.factory.yml': job.layers?.[2]?.docker_compose_yaml || '',
        };
        reply = `**5-Layer Software Factory** assembled job \`${job.job_id}\` (${stackSummary.slice(0, 4).join(', ')}). Ephemeral containers & \`docker-compose.factory.yml\` generated and QA checks passed.`;
      }
    } else if (mode === 'autonomous-team') {
      const res = await fetch('/api/v1/agents/autonomous-build', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ prompt, stack: 'fastapi', write_to_disk: false }),
      });
      if (res.ok) {
        const build = await res.json();
        generatedBackendFiles = build.generated_files || {};
        reply = `**Autonomous AI Team** (\`Architect -> Coder -> Tester\`) completed run \`${build.run_id}\` with status **${build.status}** in ${build.duration_ms}ms.`;
      }
    } else {
      const res = await fetch('/api/v1/rag/query', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ query: prompt, top_k: 4 }),
      });
      if (res.ok) {
        const rag = await res.json();
        reply = `**Offline Local RAG Brain** (${rag.total_chunks_searched} chunks searched in ${rag.duration_ms}ms):\n${rag.answer}`;
      }
    }
  } catch {
    // Graceful standalone mode if Control Plane :7000 is offline
    reply = 'Generated interactive preview in standalone UNIFORGE Workbench mode (start `python devhub.py studio` on `:7000` for full 5-Layer Factory + Terminal + LSP backend).';
  }

  const previewFiles = buildInteractivePreviewFiles(prompt, stackSummary);
  return {
    reply: reply || `Assembled UNIFORGE workspace for "${prompt}".`,
    files: { ...previewFiles, ...generatedBackendFiles },
  };
}

